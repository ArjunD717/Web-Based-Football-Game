// packages/shared/src/domain/football-data.ts

/**
 * Public, build-time-independent football data model.
 *
 * These types describe the JSON that ships with the game. Source-only fields
 * (for example `realRef`) are intentionally absent: the pipeline must never
 * copy them into generated data.
 */

export const PLAYER_POSITIONS = [
  "GK",
  "RB",
  "RWB",
  "CB",
  "LB",
  "LWB",
  "CDM",
  "CM",
  "CAM",
  "RM",
  "LM",
  "RW",
  "LW",
  "CF",
  "ST",
] as const;

export type PlayerPosition = (typeof PLAYER_POSITIONS)[number];

export const FORMATION_NAMES = [
  "4-4-2",
  "4-3-3",
  "4-3-3 (2)",
  "4-3-3 (3)",
  "4-3-3 (4)",
  "4-3-3 (5)",
  "4-2-3-1",
  "4-1-4-1",
  "3-5-2",
  "3-4-3",
  "5-3-2",
  "5-2-3",
  "4-4-1-1",
  "4-3-2-1",
  "4-1-2-1-2",
  "3-4-1-2",
] as const;

export type FormationName = (typeof FORMATION_NAMES)[number];

export const PREFERRED_FEET = ["left", "right", "both"] as const;
export type PreferredFoot = (typeof PREFERRED_FEET)[number];

export const WORK_RATES = ["low", "medium", "high"] as const;
export type WorkRate = (typeof WORK_RATES)[number];

export const BODY_TYPES = ["lean", "average", "stocky"] as const;
export type BodyType = (typeof BODY_TYPES)[number];

export const PRESS_INTENSITIES = ["low", "medium", "high"] as const;
export type PressIntensity = (typeof PRESS_INTENSITIES)[number];

export const BUILD_UP_STYLES = ["short", "balanced", "direct"] as const;
export type BuildUpStyle = (typeof BUILD_UP_STYLES)[number];

export const KIT_CHOICES = ["home", "away", "third"] as const;
export type KitChoice = (typeof KIT_CHOICES)[number];

/** FC-style six-field summary; keys mirror the source-data headings. */
export interface FaceStats {
  readonly PAC: number;
  readonly SHO: number;
  readonly PAS: number;
  readonly DRI: number;
  readonly DEF: number;
  readonly PHY: number;
}

/** Every outfield attribute, all integer-rated 1..99. */
export interface DetailedAttributes {
  readonly acceleration: number;
  readonly sprintSpeed: number;
  readonly finishing: number;
  readonly shotPower: number;
  readonly longShots: number;
  readonly volleys: number;
  readonly penalties: number;
  readonly attPosition: number;
  readonly shortPassing: number;
  readonly vision: number;
  readonly crossing: number;
  readonly longPassing: number;
  readonly fkAccuracy: number;
  readonly curve: number;
  readonly dribbling: number;
  readonly agility: number;
  readonly balance: number;
  readonly reactions: number;
  readonly ballControl: number;
  readonly composure: number;
  readonly interceptions: number;
  readonly headingAccuracy: number;
  readonly defAwareness: number;
  readonly standingTackle: number;
  readonly slidingTackle: number;
  readonly jumping: number;
  readonly stamina: number;
  readonly strength: number;
  readonly aggression: number;
}

/** Goalkeeper-only attributes; `null` for outfield players. */
export interface GoalkeeperAttributes {
  readonly diving: number;
  readonly handling: number;
  readonly kicking: number;
  readonly positioning: number;
  readonly reflexes: number;
  readonly speed: number;
}

export interface PlayerWorkRate {
  readonly att: WorkRate;
  readonly def: WorkRate;
}

/** Public player record. `realRef` must never appear here. */
export interface PlayerData {
  readonly id: string;
  /** Mutated name shipped to clients. */
  readonly name: string;
  readonly age: number;
  /** ISO calendar date, YYYY-MM-DD. */
  readonly dob: string;
  readonly nationId: string;
  readonly clubId: string;
  readonly positions: readonly PlayerPosition[];
  readonly preferredPosition: PlayerPosition;
  readonly overall: number;
  readonly potential: number;
  readonly faceStats: FaceStats;
  readonly attributes: DetailedAttributes;
  readonly goalkeeper: GoalkeeperAttributes | null;
  readonly skillMoves: number;
  readonly weakFoot: number;
  readonly workRate: PlayerWorkRate;
  readonly playStyles: readonly string[];
  readonly foot: PreferredFoot;
  readonly heightCm: number;
  readonly weightKg: number;
  readonly bodyType: BodyType;
  readonly injuryProneness: number;
  readonly kitNumber: number;
  /** Relative asset path generated by the data pipeline. */
  readonly face: string;
  readonly sample: boolean;
}

export interface TeamTactics {
  /** 0 = deep block, 100 = high line. */
  readonly defensiveDepth: number;
  /** 0 = narrow, 100 = maximum width. */
  readonly width: number;
  readonly pressIntensity: PressIntensity;
  readonly buildUpStyle: BuildUpStyle;
}

export interface TeamColours {
  readonly home: string;
  readonly away: string;
  readonly third: string;
  readonly goalkeeper: string;
}

export interface StartingSlot {
  /** Zero-based formation slot index. */
  readonly slot: number;
  readonly role: PlayerPosition;
  readonly playerId: string;
}

export interface TeamSheet {
  readonly formation: FormationName;
  /** Match kit selection; drives the primary colour sent to the renderer. */
  readonly kit: KitChoice;
  readonly startingXI: readonly StartingSlot[];
  readonly bench: readonly string[];
  readonly reserves: readonly string[];
  readonly captain: string;
  readonly penaltyTaker: string;
  readonly freeKickTaker: string;
  readonly cornerLeft: string;
  readonly cornerRight: string;
  readonly tactics: TeamTactics;
}

export interface TeamData {
  readonly id: string;
  readonly name: string;
  readonly short: string;
  readonly leagueId: string;
  readonly colours: TeamColours;
  readonly stadium: string;
  readonly managerName: string;
  readonly crest: string;
  readonly kits: {
    readonly home: string;
    readonly away: string;
    readonly third: string;
  };
  readonly squad: readonly string[];
  readonly defaultSheet: TeamSheet;
  readonly sample: boolean;
}

export interface LeagueData {
  readonly id: string;
  readonly country: string;
  readonly name: string;
  /** Only top divisions are supported. */
  readonly tier: 1;
  readonly clubIds: readonly string[];
  readonly season: string;
  readonly sample: boolean;
}

/**
 * National-team metadata is present from M6; call-up/reserve validation arrives
 * with the nation registry in M9.
 */
export interface NationData {
  readonly id: string;
  readonly name: string;
  readonly short: string;
  readonly colours: TeamColours;
  readonly squad: readonly string[];
  readonly reserves: readonly string[];
  readonly sample: boolean;
}

export interface DataManifest {
  readonly schemaVersion: number;
  readonly sample: boolean;
  readonly leagues: number;
  readonly teams: number;
  readonly players: number;
  readonly nations: number;
  readonly leagueIds: readonly string[];
  readonly teamIds: readonly string[];
}

export function isPlayerPosition(value: string): value is PlayerPosition {
  return (PLAYER_POSITIONS as readonly string[]).includes(value);
}
